#!/usr/bin/env python3
"""Subset the Lucide icon font to the icons Quarry uses.

Inputs : third_party/lucide/lucide.ttf + info.json (pinned upstream copy, ISC licence)
         scripts/icons.txt (one Lucide icon name per line, '#' comments allowed)
Outputs: src/app/assets/icons/lucide-subset.ttf
         src/app/qml/Quarry/Controls/Icons.qml  (singleton: property string <camelName>: "\\uXXXX")
         The font is aliased next to Icons.qml in the Quarry.Controls resources (src/app/CMakeLists.txt).

Usage: python scripts/subset_icons.py   (dev-only; needs `pip install fonttools`)
Re-run after editing scripts/icons.txt and commit both outputs.
"""
import json
import re
import sys
from pathlib import Path

from fontTools import subset

ROOT = Path(__file__).resolve().parent.parent
SRC_DIR = ROOT / "third_party" / "lucide"
ICON_LIST = ROOT / "scripts" / "icons.txt"
OUT_FONT = ROOT / "src" / "app" / "assets" / "icons" / "lucide-subset.ttf"
OUT_QML = ROOT / "src" / "app" / "qml" / "Quarry" / "Controls" / "Icons.qml"


def camel(name: str) -> str:
    head, *rest = name.split("-")
    out = head + "".join(p[:1].upper() + p[1:] for p in rest)
    return out if not out[0].isdigit() else "i" + out


def main() -> int:
    info = json.loads((SRC_DIR / "info.json").read_text(encoding="utf-8"))
    names = []
    for line in ICON_LIST.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            names.append(line)
    missing = [n for n in names if n not in info]
    if missing:
        print("Unknown Lucide icons: " + ", ".join(missing), file=sys.stderr)
        return 1
    if len(set(names)) != len(names):
        print("Duplicate names in icons.txt", file=sys.stderr)
        return 1

    codepoints = {}
    for n in names:
        m = re.fullmatch(r"\\([0-9a-fA-F]+)", info[n]["encodedCode"])
        if not m:
            print(f"Unexpected code for {n}: {info[n]['encodedCode']}", file=sys.stderr)
            return 1
        codepoints[n] = int(m.group(1), 16)

    OUT_FONT.parent.mkdir(parents=True, exist_ok=True)
    opts = subset.Options()
    opts.layout_features = []
    opts.name_IDs = ["*"]
    opts.notdef_outline = True
    font = subset.load_font(str(SRC_DIR / "lucide.ttf"), opts)
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=sorted(codepoints.values()))
    sub.subset(font)
    subset.save_font(font, str(OUT_FONT), opts)

    lines = [
        "// Generated by scripts/subset_icons.py from scripts/icons.txt. Do not edit by hand.",
        "// Lucide icons (ISC licence, third_party/lucide/LICENSE).",
        "pragma Singleton",
        "import QtQuick",
        "",
        "QtObject {",
        '    readonly property string fontFamily: iconFont.name',
        '    readonly property FontLoader iconFont: FontLoader { source: "lucide-subset.ttf" }',
        "",
    ]
    for n in names:
        lines.append(f'    readonly property string {camel(n)}: "\\u{codepoints[n]:04x}"')
    lines.append("}")
    OUT_QML.parent.mkdir(parents=True, exist_ok=True)
    OUT_QML.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(names)} icons -> {OUT_FONT.relative_to(ROOT)} ({OUT_FONT.stat().st_size} bytes), {OUT_QML.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
